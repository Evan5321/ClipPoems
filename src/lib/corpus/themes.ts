/** 主题词 → 语料碎片 */
export function themeWordsToFragments(pack: ThemePack) {
  return pack.words.map((text, i) => ({
    id: `theme-${pack.id}-${i}`,
    text,
    source: `主题词包 · ${pack.name}`,
    wordCount: text.length,
    tags: pack.tags,
    corpusId: 'theme_pack',
  }));
}
